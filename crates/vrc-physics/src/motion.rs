    #[test]
    fn blink_cycle_triggers_within_expected_interval() {
        let (map, mut pose) = make_humanoid_pose();
        let mut motion = AutonomousMotion::new(&map, &pose);
        let cfg = MotionConfig::default();

        let mut max_blink = 0.0f32;
        let mut saw_zero_after_blink = false;
        let mut blinked = false;

        // Simulate 7 seconds at 60 FPS -> guaranteed to hit [2.5, 6.0]s blink interval and finish.
        for _ in 0..(7 * 60) {
            pose.reset_to_rest();
            let out = motion.step(1.0 / 60.0, &mut pose, &MotionInput::default(), &cfg);
            if out.blink_weight > 0.5 {
                blinked = true;
            }
            max_blink = max_blink.max(out.blink_weight);
            if blinked && out.blink_weight == 0.0 {
                saw_zero_after_blink = true;
            }
        }

        assert!(blinked, "expected at least one blink within 7s");
        assert!(max_blink >= 0.99);
        assert!(saw_zero_after_blink, "expected eyes to reopen after blink");
    }

