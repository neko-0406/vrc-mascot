//! Autonomous mascot motion engine: idle breathing, blinking, cursor gaze, petting detector, and postures.

use std::collections::{BTreeMap, HashMap, VecDeque};
use std::f32::consts::TAU;

use glam::{EulerRot, Quat, Vec2, Vec3};
use vrc_schema::{MascotState, MotionConfig};

use crate::skeleton::SkeletonPose;

const BLINK_CLOSE_DUR: f32 = 0.06;
const BLINK_HOLD_DUR: f32 = 0.03;
const BLINK_OPEN_DUR: f32 = 0.09;
const BLINK_TOTAL_DUR: f32 = BLINK_CLOSE_DUR + BLINK_HOLD_DUR + BLINK_OPEN_DUR;

const PET_RADIUS_PX: f32 = 90.0;
const PET_MIN_STROKE_PX: f32 = 10.0;
const PET_REVERSAL_THRESHOLD: u32 = 2;
const PET_TRIGGER_COOLDOWN_SEC: f32 = 0.75;
const PET_STROKE_TIMEOUT_SEC: f32 = 1.5;
const PET_WINDOW_SEC: f32 = 60.0;

/// Per-frame external inputs passed to [`AutonomousMotion::step`].
#[derive(Debug, Clone, Copy, Default)]
pub struct MotionInput {
    pub mascot_state: MascotState,
    pub cursor_ndc: Option<Vec2>,
    pub head_screen_pos: Option<Vec2>,
    pub cursor_screen_pos: Option<Vec2>,
}

/// Output generated by one frame of [`AutonomousMotion::step`].
#[derive(Debug, Clone, Default)]
pub struct MotionFrameOutput {
    pub blink_weight: f32,
    pub blendshape_weights: HashMap<String, f32>,
    pub petting_triggered: bool,
    pub pet_count_recent: u32,
}

#[derive(Debug, Clone, Default)]
struct HumanoidIndices {
    hips: Option<usize>,
    spine: Option<usize>,
    chest: Option<usize>,
    upper_chest: Option<usize>,
    neck: Option<usize>,
    head: Option<usize>,
    left_eye: Option<usize>,
    right_eye: Option<usize>,
    left_upper_leg: Option<usize>,
    right_upper_leg: Option<usize>,
    left_lower_leg: Option<usize>,
    right_lower_leg: Option<usize>,
    left_upper_arm: Option<usize>,
    right_upper_arm: Option<usize>,
}

/// Deterministic XorShift64 PRNG for natural blink intervals without external randomness deps.
#[derive(Debug, Clone)]
struct XorShift64 {
    state: u64,
}

impl XorShift64 {
    fn new(seed: u64) -> Self {
        Self {
            state: if seed == 0 {
                0x9E37_79B9_7F4A_7C15
            } else {
                seed
            },
        }
    }

    fn next_u64(&mut self) -> u64 {
        let mut x = self.state;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.state = x;
        x
    }

    fn next_f32(&mut self) -> f32 {
        ((self.next_u64() >> 40) as f32) / ((1u64 << 24) as f32)
    }

    fn range_f32(&mut self, min: f32, max: f32) -> f32 {
        min + (max - min) * self.next_f32()
    }
}

/// Autonomous procedural animation, blinking, gaze tracking, and petting gesture recognizer.
#[derive(Debug, Clone)]
pub struct AutonomousMotion {
    bones: HumanoidIndices,
    sim_time: f32,
    rng: XorShift64,
    blink_timer: f32,
    next_blink_interval: f32,
    blink_active_time: Option<f32>,
    smoothed_gaze: Vec2,
    sit_blend: f32,
    drag_blend: f32,
    fall_blend: f32,
    // Petting detector state
    last_cursor_pos: Option<Vec2>,
    stroke_accum_dx: f32,
    last_stroke_dir: i8,
    reversals: u32,
    last_reversal_time: f32,
    last_pet_trigger_time: f32,
    pet_timestamps: VecDeque<f32>,
}

impl AutonomousMotion {
    /// Initializes autonomous motion controllers using manifest humanoid bone bindings.
    pub fn new(humanoid_bones: &BTreeMap<String, String>, rest_pose: &SkeletonPose) -> Self {
        let resolve = |key: &str| -> Option<usize> {
            humanoid_bones
                .get(key)
                .and_then(|path| rest_pose.find_node(path))
                .or_else(|| rest_pose.find_node(key))
        };

        let bones = HumanoidIndices {
            hips: resolve("Hips"),
            spine: resolve("Spine"),
            chest: resolve("Chest"),
            upper_chest: resolve("UpperChest"),
            neck: resolve("Neck"),
            head: resolve("Head"),
            left_eye: resolve("LeftEye"),
            right_eye: resolve("RightEye"),
            left_upper_leg: resolve("LeftUpperLeg"),
            right_upper_leg: resolve("RightUpperLeg"),
            left_lower_leg: resolve("LeftLowerLeg"),
            right_lower_leg: resolve("RightLowerLeg"),
            left_upper_arm: resolve("LeftUpperArm"),
            right_upper_arm: resolve("RightUpperArm"),
        };

        let mut rng = XorShift64::new(0x5EED_B11C_CAFE_1234);
        let next_blink_interval = rng.range_f32(2.5, 6.0);

        Self {
            bones,
            sim_time: 0.0,
            rng,
            blink_timer: 0.0,
            next_blink_interval,
            blink_active_time: None,
            smoothed_gaze: Vec2::ZERO,
            sit_blend: 0.0,
            drag_blend: 0.0,
            fall_blend: 0.0,
            last_cursor_pos: None,
            stroke_accum_dx: 0.0,
            last_stroke_dir: 0,
            reversals: 0,
            last_reversal_time: -10.0,
            last_pet_trigger_time: -10.0,
            pet_timestamps: VecDeque::new(),
        }
    }

    /// Resets transient motion state (blending, gaze, timers).
    pub fn reset(&mut self) {
        self.smoothed_gaze = Vec2::ZERO;
        self.sit_blend = 0.0;
        self.drag_blend = 0.0;
        self.fall_blend = 0.0;
        self.blink_timer = 0.0;
        self.blink_active_time = None;
        self.last_cursor_pos = None;
        self.stroke_accum_dx = 0.0;
        self.last_stroke_dir = 0;
        self.reversals = 0;
    }

    /// Returns the number of petting interactions recorded over the last 60 seconds.
    pub fn pet_count_recent(&self) -> u32 {
        self.pet_timestamps.len() as u32
    }

    /// Returns the current smoothed gaze NDC vector `(x, y)` in `[-1, 1]`.
    pub fn smoothed_gaze(&self) -> Vec2 {
        self.smoothed_gaze
    }

    /// Returns current sitting posture blend weight in `[0.0, 1.0]`.
    pub fn sit_blend(&self) -> f32 {
        self.sit_blend
    }

    /// Advances autonomous motion, updates `pose` local transforms, and returns blink & petting info.
    pub fn step(
        &mut self,
        dt: f32,
        pose: &mut SkeletonPose,
        input: &MotionInput,
        cfg: &MotionConfig,
    ) -> MotionFrameOutput {
        let safe_dt = if dt.is_finite() && dt > 0.0 {
            dt.min(0.25)
        } else {
            0.0
        };
        self.sim_time += safe_dt;

        // 1. Idle breathing & gentle weight shift
        if cfg.autonomous_enabled && cfg.idle_enabled {
            self.apply_idle_breathing(pose, cfg.move_speed_scale);
        }

        // 2. Posture offsets (Idle / Dragged / Falling / SeatedOnTaskbar / SeatedOnWindow)
        self.update_and_apply_postures(safe_dt, pose, input.mascot_state);

        // 3. Smooth cursor gaze & head/neck/eye tracking
        if cfg.autonomous_enabled && cfg.gaze_tracking_enabled {
            self.update_and_apply_gaze(safe_dt, pose, input.cursor_ndc);
        } else {
            let decay = 1.0 - (-8.0 * safe_dt).exp();
            self.smoothed_gaze = self.smoothed_gaze.lerp(Vec2::ZERO, decay);
        }

        // 4. Natural randomized blinking
        let blink_weight = if cfg.autonomous_enabled && cfg.blink_enabled {
            self.step_blink(safe_dt)
        } else {
            self.blink_active_time = None;
            0.0
        };

        let mut blendshape_weights = HashMap::new();
        if blink_weight > 0.0 {
            blendshape_weights.insert("blink".to_owned(), blink_weight);
            blendshape_weights.insert("Blink".to_owned(), blink_weight);
        }

        // 5. Head/cheek petting gesture detection
        let petting_triggered = if cfg.interaction_enabled {
            self.step_petting_detector(input.head_screen_pos, input.cursor_screen_pos)
        } else {
            self.reset_pet_stroke();
            false
        };

        // Prune petting history outside rolling 60s window
        let cutoff = self.sim_time - PET_WINDOW_SEC;
        while let Some(&front) = self.pet_timestamps.front() {
            if front < cutoff {
                self.pet_timestamps.pop_front();
            } else {
                break;
            }
        }

        MotionFrameOutput {
            blink_weight,
            blendshape_weights,
            petting_triggered,
            pet_count_recent: self.pet_timestamps.len() as u32,
        }
    }

    fn apply_idle_breathing(&self, pose: &mut SkeletonPose, speed_scale: f32) {
        let speed = speed_scale.clamp(0.1, 3.0);
        let t = self.sim_time * speed;
        let breath_phase = t * TAU * 0.28; // ~3.57s breath cycle
        let breath = breath_phase.sin();

        // Chest / UpperChest subtle pitch
        let chest_pitch = breath * 0.025; // ~1.4 deg
        if let Some(idx) = self.bones.chest.or(self.bones.upper_chest) {
            pose.apply_local_rotation_offset(idx, Quat::from_rotation_x(chest_pitch));
        }

        // Spine gentle sway & counter-breath
        let spine_yaw = (t * 0.65).sin() * 0.015;
        let spine_roll = (t * 0.45).cos() * 0.012;
        if let Some(idx) = self.bones.spine {
            pose.apply_local_rotation_offset(
                idx,
                Quat::from_euler(EulerRot::YXZ, spine_yaw, breath * 0.012, spine_roll),
            );
        }

        // Hips subtle weight shift
        if let Some(idx) = self.bones.hips {
            let rest_t = pose.nodes()[idx].rest_translation;
            let shift = Vec3::new((t * 0.45).sin() * 0.008, breath * 0.003, 0.0);
            pose.set_local_translation(idx, rest_t + shift);
            pose.apply_local_rotation_offset(idx, Quat::from_rotation_z(-(t * 0.45).sin() * 0.01));
        }
    }

    fn update_and_apply_postures(
        &mut self,
        dt: f32,
        pose: &mut SkeletonPose,
        mascot_state: MascotState,
    ) {
        let sit_target = match mascot_state {
            MascotState::SeatedOnTaskbar | MascotState::SeatedOnWindow => 1.0,
            _ => 0.0,
        };
        let drag_target = if mascot_state == MascotState::Dragged {
            1.0
        } else {
            0.0
        };
        let fall_target = if mascot_state == MascotState::Falling {
            1.0
        } else {
            0.0
        };

        let blend_alpha = 1.0 - (-8.0 * dt).exp();
        self.sit_blend += (sit_target - self.sit_blend) * blend_alpha;
        self.drag_blend += (drag_target - self.drag_blend) * blend_alpha;
        self.fall_blend += (fall_target - self.fall_blend) * blend_alpha;

        // Sitting pose: bend hips/upper legs forward and lower legs downward.
        if self.sit_blend > 1e-4 {
            let w = self.sit_blend;
            let upper_leg_pitch = -78.0f32.to_radians() * w;
            let lower_leg_pitch = 78.0f32.to_radians() * w;
            let splay = 6.0f32.to_radians() * w;

            if let Some(idx) = self.bones.left_upper_leg {
                pose.apply_local_rotation_offset(
                    idx,
                    Quat::from_euler(EulerRot::YXZ, 0.0, upper_leg_pitch, splay),
                );
            }
            if let Some(idx) = self.bones.right_upper_leg {
                pose.apply_local_rotation_offset(
                    idx,
                    Quat::from_euler(EulerRot::YXZ, 0.0, upper_leg_pitch, -splay),
                );
            }
            if let Some(idx) = self.bones.left_lower_leg {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_x(lower_leg_pitch));
            }
            if let Some(idx) = self.bones.right_lower_leg {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_x(lower_leg_pitch));
            }
            if let Some(idx) = self.bones.hips {
                let curr_t = pose.local_transforms()[idx].0;
                pose.set_local_translation(idx, curr_t + Vec3::new(0.0, -0.15 * w, 0.0));
            }
        }

        // Dragged pose: gentle dangling legs and slightly raised arms.
        if self.drag_blend > 1e-4 {
            let w = self.drag_blend;
            let dangle = (self.sim_time * 4.5).sin() * 8.0f32.to_radians() * w;
            let knee_bend = 18.0f32.to_radians() * w;
            let arm_out = 18.0f32.to_radians() * w;

            if let Some(idx) = self.bones.left_upper_leg {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_x(dangle));
            }
            if let Some(idx) = self.bones.right_upper_leg {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_x(-dangle));
            }
            if let Some(idx) = self.bones.left_lower_leg {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_x(knee_bend));
            }
            if let Some(idx) = self.bones.right_lower_leg {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_x(knee_bend));
            }
            if let Some(idx) = self.bones.left_upper_arm {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_z(arm_out));
            }
            if let Some(idx) = self.bones.right_upper_arm {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_z(-arm_out));
            }
        }

        // Falling pose: arms raised wider and gentle leg flail.
        if self.fall_blend > 1e-4 {
            let w = self.fall_blend;
            let arm_raise = 38.0f32.to_radians() * w;
            let leg_flail = (self.sim_time * 9.0).sin() * 12.0f32.to_radians() * w;

            if let Some(idx) = self.bones.left_upper_arm {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_z(arm_raise));
            }
            if let Some(idx) = self.bones.right_upper_arm {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_z(-arm_raise));
            }
            if let Some(idx) = self.bones.left_upper_leg {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_x(leg_flail));
            }
            if let Some(idx) = self.bones.right_upper_leg {
                pose.apply_local_rotation_offset(idx, Quat::from_rotation_x(-leg_flail));
            }
        }
    }

    fn update_and_apply_gaze(
        &mut self,
        dt: f32,
        pose: &mut SkeletonPose,
        cursor_ndc: Option<Vec2>,
    ) {
        let target = match cursor_ndc {
            Some(ndc) if ndc.is_finite() => ndc.clamp(Vec2::splat(-1.0), Vec2::splat(1.0)),
            _ => Vec2::ZERO,
        };
        let alpha = 1.0 - (-8.0 * dt).exp();
        self.smoothed_gaze = self.smoothed_gaze.lerp(target, alpha);

        let gx = self.smoothed_gaze.x.clamp(-1.0, 1.0);
        let gy = self.smoothed_gaze.y.clamp(-1.0, 1.0);

        // Neck (~10 deg yaw, ~7 deg pitch)
        if let Some(idx) = self.bones.neck {
            let yaw = gx * 10.0f32.to_radians();
            let pitch = -gy * 7.0f32.to_radians();
            pose.apply_local_rotation_offset(idx, Quat::from_euler(EulerRot::YXZ, yaw, pitch, 0.0));
        }

        // Head (~25 deg yaw, ~18 deg pitch)
        if let Some(idx) = self.bones.head {
            let yaw = gx * 25.0f32.to_radians();
            let pitch = -gy * 18.0f32.to_radians();
            pose.apply_local_rotation_offset(idx, Quat::from_euler(EulerRot::YXZ, yaw, pitch, 0.0));
        }

        // Eyes (~15 deg yaw, ~10 deg pitch)
        let eye_yaw = gx * 15.0f32.to_radians();
        let eye_pitch = -gy * 10.0f32.to_radians();
        let eye_rot = Quat::from_euler(EulerRot::YXZ, eye_yaw, eye_pitch, 0.0);
        if let Some(idx) = self.bones.left_eye {
            pose.apply_local_rotation_offset(idx, eye_rot);
        }
        if let Some(idx) = self.bones.right_eye {
            pose.apply_local_rotation_offset(idx, eye_rot);
        }
    }

    fn step_blink(&mut self, dt: f32) -> f32 {
        if let Some(elapsed) = &mut self.blink_active_time {
            *elapsed += dt;
            let t = *elapsed;
            if t < BLINK_CLOSE_DUR {
                (t / BLINK_CLOSE_DUR).clamp(0.0, 1.0)
            } else if t < BLINK_CLOSE_DUR + BLINK_HOLD_DUR {
                1.0
            } else if t < BLINK_TOTAL_DUR {
                let open_t = t - (BLINK_CLOSE_DUR + BLINK_HOLD_DUR);
                (1.0 - open_t / BLINK_OPEN_DUR).clamp(0.0, 1.0)
            } else {
                self.blink_active_time = None;
                self.blink_timer = 0.0;
                self.next_blink_interval = self.rng.range_f32(2.5, 6.0);
                0.0
            }
        } else {
            self.blink_timer += dt;
            if self.blink_timer >= self.next_blink_interval {
                self.blink_active_time = Some(0.0);
                // Start closing smoothly
                0.0
            } else {
                0.0
            }
        }
    }

    fn step_petting_detector(
        &mut self,
        head_screen_pos: Option<Vec2>,
        cursor_screen_pos: Option<Vec2>,
    ) -> bool {
        let (Some(head), Some(cursor)) = (head_screen_pos, cursor_screen_pos) else {
            self.reset_pet_stroke();
            return false;
        };
        if !head.is_finite() || !cursor.is_finite() {
            self.reset_pet_stroke();
            return false;
        }

        if cursor.distance(head) > PET_RADIUS_PX {
            self.reset_pet_stroke();
            return false;
        }

        if self.sim_time - self.last_reversal_time > PET_STROKE_TIMEOUT_SEC {
            self.reversals = 0;
        }

        let mut triggered = false;
        if let Some(prev) = self.last_cursor_pos {
            let dx = cursor.x - prev.x;
            self.stroke_accum_dx += dx;

            if self.stroke_accum_dx.abs() >= PET_MIN_STROKE_PX {
                let dir = if self.stroke_accum_dx > 0.0 { 1 } else { -1 };
                if self.last_stroke_dir != 0 && dir != self.last_stroke_dir {
                    self.reversals += 1;
                    self.last_reversal_time = self.sim_time;
                }
                self.last_stroke_dir = dir;
                self.stroke_accum_dx = 0.0;

                if self.reversals >= PET_REVERSAL_THRESHOLD
                    && (self.sim_time - self.last_pet_trigger_time) >= PET_TRIGGER_COOLDOWN_SEC
                {
                    triggered = true;
                    self.last_pet_trigger_time = self.sim_time;
                    self.pet_timestamps.push_back(self.sim_time);
                    self.reversals = 0;
                }
            }
        }

        self.last_cursor_pos = Some(cursor);
        triggered
    }

    fn reset_pet_stroke(&mut self) {
        self.last_cursor_pos = None;
        self.stroke_accum_dx = 0.0;
        self.last_stroke_dir = 0;
        self.reversals = 0;
    }
}

